#!/usr/bin/env python3
"""Write requirements.lock: exact versions of what the gateway runs on now.

    python3 tools/freeze_lock.py            # writes requirements.lock
    python3 tools/freeze_lock.py --check    # exit 1 if this Python differs from it

Run it on the gateway with the Python the service uses. It starts from the
packages requirements.txt names (plus protobuf, pinned for pymumble), walks
their installed dependencies, and records name==version for each. Nothing
unrelated on the box ends up in the lock.

scripts/venv.sh installs the lock with --no-deps, so the venv gets exactly
these versions and nothing pip would resolve differently: no torch pulled in
by silero-vad, no protobuf upgrade from onnxruntime.

Editable installs (kv4p-ht-python, cloned to ~/kv4p-ht-python) are left out;
venv.sh installs those from their checkout.
"""

import importlib.metadata as md
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REQ = os.path.join(REPO, 'requirements.txt')
LOCK = os.path.join(REPO, 'requirements.lock')
EXTRA_ROOTS = ('protobuf', 'pymumble', 'pymumble-py3', 'setuptools')


def norm(name):
    return re.sub(r'[-_.]+', '-', name).strip().lower()


def roots():
    out = set(EXTRA_ROOTS)
    with open(REQ) as f:
        for line in f:
            line = line.split('#', 1)[0].split(';', 1)[0].strip()
            m = re.match(r'^[A-Za-z0-9][A-Za-z0-9._-]*', line)
            if m:
                out.add(m.group(0))
    return {norm(r) for r in out}


def installed():
    dists = {}
    for d in md.distributions():
        name = d.metadata.get('Name')
        if name:
            dists.setdefault(norm(name), d)
    return dists


def is_editable(dist):
    try:
        direct = dist.read_text('direct_url.json') or ''
    except Exception:
        direct = ''
    return '"editable": true' in direct.replace("'", '"')


def closure(dists):
    todo, seen = list(roots()), set()
    while todo:
        name = todo.pop()
        if name in seen or name not in dists:
            continue
        seen.add(name)
        for req in dists[name].requires or []:
            if 'extra ==' in req:
                continue
            m = re.match(r'^[A-Za-z0-9][A-Za-z0-9._-]*', req)
            if m:
                todo.append(norm(m.group(0)))
    return seen


def lock_lines():
    dists = installed()
    lines = []
    for name in sorted(closure(dists)):
        d = dists[name]
        if is_editable(d):
            continue
        lines.append(f"{d.metadata['Name']}=={d.version}")
    return lines


def main():
    if '--check' in sys.argv:
        # Only the locked packages matter; anything else this Python can see
        # (system site-packages under a venv) is not the lock's business.
        dists = installed()
        bad = 0
        with open(LOCK) as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith('#'):
                    continue
                name, _, want = line.partition('==')
                d = dists.get(norm(name))
                have = d.version if d else None
                if have != want:
                    bad += 1
                    print(f"  {name}: lock {want}, this python {have or 'missing'}")
        return 1 if bad else 0
    lines = lock_lines()
    with open(LOCK, 'w') as f:
        f.write(f"# Generated by tools/freeze_lock.py from {sys.executable}\n"
                f"# Python {sys.version.split()[0]}. Install with --no-deps "
                f"(scripts/venv.sh does).\n")
        f.write('\n'.join(lines) + '\n')
    print(f"wrote {LOCK}: {len(lines)} packages")
    return 0


if __name__ == '__main__':
    sys.exit(main())
